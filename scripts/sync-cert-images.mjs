// Lists the certification cover images in public/images/certifications so the site knows which exist.
// Runs automatically before `npm run build` / `npm run dev`. Add an image named <certification-id>.jpg and rebuild.
import { readdirSync, writeFileSync } from "node:fs";

const dir = "public/images/certifications";
const ids = readdirSync(dir)
  .filter((f) => /^cert-[a-z0-9-]+\.jpg$/.test(f))
  .map((f) => f.replace(/\.jpg$/, ""))
  .sort();

writeFileSync(
  "src/data/cert-images.ts",
  `// Generated by scripts/sync-cert-images.mjs. Do not edit by hand.\nexport const CERT_IMAGE_IDS: ReadonlySet<string> = new Set(${JSON.stringify(ids, null, 2)});\n`,
);
console.log(`[cert-images] ${ids.length} certification images`);
